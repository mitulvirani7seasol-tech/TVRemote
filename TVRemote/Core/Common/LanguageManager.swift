@MainActor
final class TR_LanguageManager: ObservableObject {
    static let shared = TR_LanguageManager()
    
    private let selectedLanguageKey = "AppSelectedLanguageCode"
    private let hasCompletedLanguageSelectionKey = "HasCompletedLanguageSelection"
    private let hasCompletedOnboardingKey = "HasCompletedOnboarding"
    
    @Published var currentLanguage: LanguageItem
    @Published var hasSelectedLanguage: Bool
    @Published var hasCompletedOnboarding: Bool
    
    init() {
        let savedCode = UserDefaults.standard.string(forKey: "AppSelectedLanguageCode") ?? "en"
        let found = LanguageItem.allLanguages.first(where: { $0.code == savedCode }) ?? LanguageItem.allLanguages[0]
        self.currentLanguage = found
        self.hasSelectedLanguage = UserDefaults.standard.bool(forKey: "HasCompletedLanguageSelection")
        self.hasCompletedOnboarding = UserDefaults.standard.bool(forKey: "HasCompletedOnboarding")
    }
    
    func selectLanguage(_ item: LanguageItem) {
        self.currentLanguage = item
        self.hasSelectedLanguage = true
        UserDefaults.standard.set(item.code, forKey: selectedLanguageKey)
        UserDefaults.standard.set(true, forKey: hasCompletedLanguageSelectionKey)
    }
    
    func completeOnboarding() {
        self.hasCompletedOnboarding = true
        UserDefaults.standard.set(true, forKey: hasCompletedOnboardingKey)
    }
    
    // Real-time dynamic localization dictionary for all 14 supported languages
    func localized(_ key: String, langCode: String? = nil) -> String {
        let code = langCode ?? currentLanguage.code
        guard let dict = TR_LanguageManager.translations[code] ?? TR_LanguageManager.translations["en"] else {
            return key
        }
        return dict[key] ?? TR_LanguageManager.translations["en"]?[key] ?? key
    }
    
